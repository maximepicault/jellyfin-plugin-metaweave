    /// <summary>Content of a local source: series → seasons → episodes</summary>
    public class LocalContent
    {
        public int Version { get; set; } = 1;
        public List<LocalSeries> Series { get; set; } = new List<LocalSeries>();
    }

    /// <summary>Fields shared by series, seasons and episodes (the names follow the default mappings)</summary>
    public class LocalNode
    {
        /// <summary>Short identifier generated by the plugin: the {prefix-ID} of file/folder names</summary>
        public string Id { get; set; }
        public string Title { get; set; }
        public string Overview { get; set; }

        /// <summary>yyyy-MM-dd</summary>
        public string PremiereDate { get; set; }
        public float? CommunityRating { get; set; }
        public List<string> Tags { get; set; } = new List<string>();
        public List<string> Genres { get; set; } = new List<string>();
        public string Poster { get; set; }
        public string Backdrop { get; set; }
        public string Banner { get; set; }
        public string Logo { get; set; }
        public string Thumb { get; set; }
    }

    public class LocalSeries : LocalNode
    {
        public List<LocalSeason> Seasons { get; set; } = new List<LocalSeason>();
    }

    public class LocalSeason : LocalNode
    {
        public List<LocalEpisode> Episodes { get; set; } = new List<LocalEpisode>();
    }

    public class LocalEpisode : LocalNode
    {
        public int? IndexNumber { get; set; }

        /// <summary>"mm:ss", "hh:mm:ss", seconds or ISO 8601 (see DurationParser)</summary>
        public string Duration { get; set; }

        /// <summary>URL of the preview video (missing episodes only)</summary>
        public string PreviewUrl { get; set; }

        /// <summary>Cast: people of the directory (PeopleStore), with their role in THIS episode</summary>
        public List<LocalCastEntry> Cast { get; set; } = new List<LocalCastEntry>();
    }

    public class LocalCastEntry
    {
        /// <summary>Person.Id in the directory</summary>
        public string PersonId { get; set; }

        /// <summary>Role (character, function…)</summary>
        public string Role { get; set; }

        /// <summary>Nom d'un PersonKind de Jellyfin : Actor, GuestStar, Director, Writer, Producer, Composer…</summary>
        public string Type { get; set; } = "Actor";
    }

    /// <summary>
    /// Storage and serving of local sources. One JSON file per source (DataFolderPath/local-sources/{LocalDataId}.json).
    /// <see cref="Serve"/> answers in place of the API with the same JSON that the default mappings can read
    /// (title, overview, premiereDate, tags, genres, poster, thumb, preview.url…), from the same URLs
    /// as the default endpoints: /series/{id}, /sources/{id}, /sources/{id}/videos, /videos/{id}.
    /// </summary>
    public class LocalSourceStore
    {
        public const string BaseUrl = "local://local";
        public const string VideoEndpoint = "/videos/{id}";
        public const string SourceEndpoint = "/sources/{id}";
        public const string SeriesEndpoint = "/series/{id}";
        public const string EpisodeListEndpoint = "/sources/{id}/videos";

        private const string Alphabet = "abcdefghjkmnpqrstuvwxyz23456789";
        private static readonly Regex DataIdPattern = new Regex(@"^[A-Za-z0-9\-]{8,64}$", RegexOptions.Compiled);
        private static readonly JsonSerializerOptions FileOptions = new JsonSerializerOptions { WriteIndented = true, PropertyNameCaseInsensitive = true };

        private readonly ILogger _logger;
        private readonly object _lock = new object();
        private readonly Dictionary<string, (DateTime Stamp, LocalContent Content)> _memory = new Dictionary<string, (DateTime, LocalContent)>();

        private readonly Func<PeopleStore> _people;

        /// <param name="people">Directory of people, to resolve the episodes' casts (supplied afterwards: it depends on this store)</param>
        public LocalSourceStore(ILogger logger, Func<PeopleStore> people = null)
        {
            _logger = logger;
            _people = people;
        }

        /// <summary>Address of an image uploaded into the plugin: "local://img/{dataId}/{file}" (read without network)</summary>
        public const string ImageUrlPrefix = "local://img/";
        public const int MaxImageBytes = 8 * 1024 * 1024;
        private static readonly Regex ImageFilePattern = new Regex(@"^[A-Za-z0-9_\-]{1,60}\.(jpg|png|webp|gif)$", RegexOptions.Compiled);

        public static bool IsLocalImageUrl(string url) => !string.IsNullOrEmpty(url) && url.StartsWith(ImageUrlPrefix, StringComparison.OrdinalIgnoreCase);

        public static bool IsValidDataId(string dataId) => !string.IsNullOrEmpty(dataId) && DataIdPattern.IsMatch(dataId);

        private static string Folder()
        {
            var root = Plugin.Instance?.DataFolderPath ?? Path.Combine(Path.GetTempPath(), "CustomMetadata");
            return Path.Combine(root, "local-sources");
        }

        private static string FilePath(string dataId) => Path.Combine(Folder(), dataId + ".json");

        /// <summary>Content of a source (empty if the file does not exist yet)</summary>
        public LocalContent Load(string dataId)
        {
            if (!IsValidDataId(dataId))
            {
                return new LocalContent();
            }

            lock (_lock)
            {
                var path = FilePath(dataId);
                if (!File.Exists(path))
                {
                    return new LocalContent();
                }

                var stamp = File.GetLastWriteTimeUtc(path);
                if (_memory.TryGetValue(dataId, out var cached) && cached.Stamp == stamp)
                {
                    return cached.Content;
                }

                try
                {
                    var content = JsonSerializer.Deserialize<LocalContent>(File.ReadAllText(path), FileOptions) ?? new LocalContent();
                    DecodeText(content);
                    _memory[dataId] = (stamp, content);
                    return content;
                }
                catch (Exception ex)
                {
                    _logger.LogError(ex, "🗂️ [LOCAL SOURCE] ❌ Cannot read {Path}", path);
                    return new LocalContent();
                }
            }
        }

        /// <summary>Normalises (ids, texts, dates) then writes the file atomically. Returns the saved content.</summary>
        public LocalContent Save(string dataId, LocalContent content)
        {
            if (!IsValidDataId(dataId))
            {
                throw new ArgumentException("Identifiant de données invalide");
            }

            content ??= new LocalContent();
            Normalize(content);

            lock (_lock)
            {
                Directory.CreateDirectory(Folder());
                var path = FilePath(dataId);
                var tmp = path + ".tmp";
                File.WriteAllText(tmp, JsonSerializer.Serialize(content, FileOptions));
                if (File.Exists(path))
                {
                    File.Copy(path, path + ".bak", true);
                }

                File.Move(tmp, path, true);
                _memory[dataId] = (File.GetLastWriteTimeUtc(path), content);
                PruneImages(dataId, content);
            }

            _logger.LogInformation("🗂️ [LOCAL SOURCE] 💾 Saved {Series} series / {Seasons} seasons / {Episodes} episodes ({DataId})",
                content.Series.Count, content.Series.Sum(s => s.Seasons.Count), content.Series.Sum(s => s.Seasons.Sum(x => x.Episodes.Count)), dataId);
            return content;
        }

        // ---- Uploaded images (stored next to the content) -----------------------------------------------------------

        private static string ImagesFolder(string dataId) => Path.Combine(Folder(), dataId + "-images");

        /// <summary>Real type from the first bytes (the name or header sent by the browser do not count)</summary>
        public static (string Mime, string Extension)? DetectImage(byte[] d)
        {
            if (d == null || d.Length < 12) return null;
            if (d[0] == 0xFF && d[1] == 0xD8 && d[2] == 0xFF) return ("image/jpeg", ".jpg");
            if (d[0] == 0x89 && d[1] == 0x50 && d[2] == 0x4E && d[3] == 0x47) return ("image/png", ".png");
            if (d[0] == 'G' && d[1] == 'I' && d[2] == 'F' && d[3] == '8') return ("image/gif", ".gif");
            if (d[0] == 'R' && d[1] == 'I' && d[2] == 'F' && d[3] == 'F' && d[8] == 'W' && d[9] == 'E' && d[10] == 'B' && d[11] == 'P') return ("image/webp", ".webp");
            return null;
        }

        /// <summary>Saves an uploaded image and returns its "local://img/…" address (null + error if refused)</summary>
        public string SaveImage(string dataId, string nodeId, byte[] data, out string error)
        {
            error = null;
            if (!IsValidDataId(dataId)) { error = "Identifiant de données invalide"; return null; }
            if (data == null || data.Length == 0) { error = "Fichier vide"; return null; }
            if (data.Length > MaxImageBytes) { error = $"Image trop lourde (maximum {MaxImageBytes / 1024 / 1024} Mo)"; return null; }
            var kind = DetectImage(data);
            if (kind == null) { error = "Format non reconnu (JPEG, PNG, WebP ou GIF attendu)"; return null; }

            var node = !string.IsNullOrEmpty(nodeId) && Regex.IsMatch(nodeId, @"^\w{1,40}$") ? nodeId : "img";
            var name = $"{node}-{Convert.ToHexString(RandomNumberGenerator.GetBytes(3)).ToLowerInvariant()}{kind.Value.Extension}";
            lock (_lock)
            {
                Directory.CreateDirectory(ImagesFolder(dataId));
                File.WriteAllBytes(Path.Combine(ImagesFolder(dataId), name), data);
            }

            _logger.LogInformation("🗂️ [LOCAL SOURCE] 🖼️ Image saved {Name} ({Size} bytes, {Mime})", name, data.Length, kind.Value.Mime);
            return $"{ImageUrlPrefix}{dataId}/{name}";
        }

        public bool TryReadImage(string dataId, string file, out byte[] data, out string mime)
        {
            data = null;
            mime = null;
            if (!IsValidDataId(dataId) || string.IsNullOrEmpty(file) || !ImageFilePattern.IsMatch(file))
            {
                return false;
            }

            var path = Path.Combine(ImagesFolder(dataId), file);
            if (!File.Exists(path))
            {
                return false;
            }

            data = File.ReadAllBytes(path);
            mime = DetectImage(data)?.Mime;
            return mime != null;
        }

        /// <summary>"local://img/{dataId}/{file}" → bytes and type</summary>
        public bool TryReadImage(string url, out byte[] data, out string mime)
        {
            data = null;
            mime = null;
            if (!IsLocalImageUrl(url))
            {
                return false;
            }

            var parts = url.Substring(ImageUrlPrefix.Length).Split('/');
            return parts.Length == 2 && TryReadImage(parts[0], parts[1], out data, out mime);
        }

        private void PruneImages(string dataId, LocalContent content)
        {
            PruneImages(dataId, AllNodes(content).SelectMany(n => new[] { n.Poster, n.Backdrop, n.Banner, n.Logo, n.Thumb }));
        }

        /// <summary>Deletes the images older than one day that none of the given addresses references (uploaded then abandoned, or removed)</summary>
        public void PruneImages(string dataId, IEnumerable<string> usedUrls)
        {
            var folder = ImagesFolder(dataId);
            if (!Directory.Exists(folder))
            {
                return;
            }

            var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var url in usedUrls ?? Enumerable.Empty<string>())
            {
                if (IsLocalImageUrl(url))
                {
                    used.Add(url.Substring(url.LastIndexOf('/') + 1));
                }
            }

            foreach (var file in Directory.GetFiles(folder))
            {
                if (!used.Contains(Path.GetFileName(file)) && File.GetLastWriteTimeUtc(file) < DateTime.UtcNow.AddDays(-1))
                {
                    File.Delete(file);
                }
            }
        }

        private static IEnumerable<LocalNode> AllNodes(LocalContent content)
        {
            foreach (var series in content.Series ?? new List<LocalSeries>())
            {
                yield return series;
                foreach (var season in series.Seasons ?? new List<LocalSeason>())
                {
                    yield return season;
                    foreach (var episode in season.Episodes ?? new List<LocalEpisode>())
                    {
                        yield return episode;
                    }
                }
            }
        }

        /// <summary>Deletes the file of a deleted local source (a .deleted copy is kept)</summary>
        public void Delete(string dataId)
        {
            if (!IsValidDataId(dataId))
            {
                return;
            }

            lock (_lock)
            {
                var path = FilePath(dataId);
                if (File.Exists(path))
                {
                    File.Move(path, path + ".deleted", true);
                }

                var images = ImagesFolder(dataId);
                if (Directory.Exists(images))
                {
                    // A ".deleted" copy from a previous deletion (same identifier) is replaced
                    var graveyard = images + ".deleted";
                    if (Directory.Exists(graveyard))
                    {
                        Directory.Delete(graveyard, true);
                    }

                    Directory.Move(images, graveyard);
                }

                _memory.Remove(dataId);
            }
        }

        // ---- Normalisation -------------------------------------------------------------------------------------

        private static string NewId(HashSet<string> used)
        {
            while (true)
            {
                var chars = new char[6];
                for (var i = 0; i < chars.Length; i++)
                {
                    chars[i] = Alphabet[RandomNumberGenerator.GetInt32(Alphabet.Length)];
                }

                var id = new string(chars);
                if (used.Add(id))
                {
                    return id;
                }
            }
        }

        private static string Clean(string text) => string.IsNullOrWhiteSpace(text) ? null : text.Trim();

        private static List<string> CleanList(List<string> list)
        {
            return (list ?? new List<string>())
                .Select(t => Clean(HtmlText.Decode(t)))
                .Where(x => x != null)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
        }

        // "prefix-id": the tag of an element of ANOTHER source, which this node overrides (series, seasons and episodes)
        private static readonly Regex OverrideId = new Regex(@"^[\w]{1,20}-[\w]{1,40}$", RegexOptions.Compiled);

        private static void NormalizeNode(LocalNode node, HashSet<string> used, bool mayOverride = false)
        {
            var id = Clean(node.Id);
            // Id: letters/digits/_ only (it ends up in a {prefix-ID} file name), unique within the source. A series or a
            // season may also carry "prefix-id" (the tag of an API element): its content then replaces that element's
            var valid = id != null && (Regex.IsMatch(id, @"^[\w]{1,40}$") || (mayOverride && OverrideId.IsMatch(id)));
            node.Id = valid && used.Add(id) ? id : NewId(used);
            // Typed text is stored decoded: titles pasted from a web page ("Q&amp;A") do not keep their
            // entities in the editor nor in "Copier le nom" (a file name with "&amp;" in it)
            node.Title = Clean(HtmlText.Decode(node.Title));
            node.Overview = Clean(HtmlText.Decode(node.Overview));
            node.PremiereDate = DateTime.TryParseExact(node.PremiereDate?.Trim(), "yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture, System.Globalization.DateTimeStyles.None, out var date)
                ? date.ToString("yyyy-MM-dd")
                : null;
            node.Tags = CleanList(node.Tags);
            node.Genres = CleanList(node.Genres);
            node.Poster = Clean(node.Poster);
            node.Backdrop = Clean(node.Backdrop);
            node.Banner = Clean(node.Banner);
            node.Logo = Clean(node.Logo);
            node.Thumb = Clean(node.Thumb);
        }

        /// <summary>A valid PersonKind name (otherwise Actor)</summary>
        public static string NormalizeCastType(string type)
        {
            return Enum.TryParse<Jellyfin.Data.Enums.PersonKind>(type?.Trim(), true, out var kind) && Enum.IsDefined(kind) && kind != Jellyfin.Data.Enums.PersonKind.Unknown
                ? kind.ToString()
                : "Actor";
        }

        /// <summary>The same person with the same job: two entries like that are one (a person may hold several jobs)</summary>
        public static bool SameCastEntry(LocalCastEntry a, LocalCastEntry b)
            => string.Equals(a.PersonId?.Trim(), b.PersonId?.Trim(), StringComparison.OrdinalIgnoreCase)
               && string.Equals(NormalizeCastType(a.Type), NormalizeCastType(b.Type), StringComparison.Ordinal);

        /// <summary>
        /// Clean cast: role trimmed, type = a valid PersonKind (otherwise Actor). One entry per person AND job: the same person
        /// can be actor and director of the same element, but not twice actor.
        /// </summary>
        public static List<LocalCastEntry> NormalizeCast(IEnumerable<LocalCastEntry> cast)
        {
            return (cast ?? Enumerable.Empty<LocalCastEntry>())
                .Where(c => !string.IsNullOrWhiteSpace(c?.PersonId))
                .GroupBy(c => c.PersonId.Trim().ToLowerInvariant() + "|" + NormalizeCastType(c.Type), StringComparer.Ordinal)
                .Select(g => new LocalCastEntry
                {
                    PersonId = g.First().PersonId.Trim(),
                    Role = Clean(HtmlText.Decode(g.First().Role)),
                    Type = NormalizeCastType(g.First().Type)
                })
                .ToList();
        }

        /// <summary>Fills in missing or duplicate ids, cleans the texts</summary>
        public static void Normalize(LocalContent content)
        {
            var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            content.Series ??= new List<LocalSeries>();
            foreach (var series in content.Series)
            {
                NormalizeNode(series, used, true);
                series.Seasons ??= new List<LocalSeason>();
                foreach (var season in series.Seasons)
                {
                    NormalizeNode(season, used, true);
                    season.Episodes ??= new List<LocalEpisode>();
                    foreach (var episode in season.Episodes)
                    {
                        NormalizeNode(episode, used, true);
                        episode.Duration = Clean(episode.Duration);
                        episode.PreviewUrl = Clean(episode.PreviewUrl);
                        episode.Cast = NormalizeCast(episode.Cast);
                        if (episode.IndexNumber is int n && n < 0)
                        {
                            episode.IndexNumber = null;
                        }
                    }
                }
            }
        }

        /// <summary>Decodes the HTML entities of the texts (ids untouched): files saved before this behaviour</summary>
        private static void DecodeText(LocalContent content)
        {
            foreach (var series in content.Series ?? new List<LocalSeries>())
            {
                var nodes = new List<LocalNode> { series };
                nodes.AddRange(series.Seasons ?? new List<LocalSeason>());
                nodes.AddRange((series.Seasons ?? new List<LocalSeason>()).SelectMany(s => s.Episodes ?? new List<LocalEpisode>()));
                foreach (var node in nodes)
                {
                    node.Title = HtmlText.Decode(node.Title);
                    node.Overview = HtmlText.Decode(node.Overview);
                    node.Tags = HtmlText.Decode(node.Tags);
                    node.Genres = HtmlText.Decode(node.Genres);
                }
            }
        }

        // ---- Overriding an element of another source --------------------------------------------------------------

        /// <summary>
        /// The local series ("series"), season ("season") or episode ("episode") whose id is the tag "prefix-id" of an element of another
        /// source: its content replaces what that source says. Only enabled local sources, never the source's own prefix.
        /// </summary>
        public (SourceConfiguration Source, LocalNode Node)? FindOverride(string tag, string kind)
        {
            if (string.IsNullOrWhiteSpace(tag) || !OverrideId.IsMatch(tag.Trim()))
            {
                return null;
            }

            tag = tag.Trim();
            var prefix = tag.Substring(0, tag.IndexOf('-'));
            foreach (var source in Plugin.Instance?.Configuration?.Sources?.Where(s => s.IsLocal && s.Enabled && !string.IsNullOrEmpty(s.LocalDataId)) ?? Enumerable.Empty<SourceConfiguration>())
            {
                if (string.Equals((source.Prefix ?? string.Empty).Trim(), prefix, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                var content = Load(source.LocalDataId);
                IEnumerable<LocalNode> nodes = kind == "series"
                    ? content.Series
                    : kind == "season"
                        ? content.Series.SelectMany(s => s.Seasons)
                        : content.Series.SelectMany(s => s.Seasons).SelectMany(s => s.Episodes);
                var node = nodes.FirstOrDefault(n => IdEquals(n.Id, tag));
                if (node != null)
                {
                    return (source, node);
                }
            }

            return null;
        }

        // ---- Serving in place of the API ------------------------------------------------------------------------

        /// <summary>Answers a "local://local/videos/abc" URL as the API would (200 + JSON, or 404)</summary>
        public HttpFetchResult Serve(SourceConfiguration source, string url)
        {
            var result = new HttpFetchResult { Url = url, Attempts = 1, HttpVersion = "local", StatusCode = 404 };

            string path;
            try
            {
                path = Uri.UnescapeDataString(new Uri(url).AbsolutePath).Trim('/');
            }
            catch (UriFormatException)
            {
                result.Error = "URL locale invalide";
                return result;
            }

            var parts = path.Split('/', StringSplitOptions.RemoveEmptyEntries);
            var content = Load(source?.LocalDataId);
            object json = null;

            if (parts.Length == 2 && parts[0] == "series")
            {
                var series = content.Series.FirstOrDefault(s => IdEquals(s.Id, parts[1]));
                json = series == null ? null : NodeJson(series);
            }
            else if (parts.Length == 2 && parts[0] == "sources")
            {
                var season = content.Series.SelectMany(s => s.Seasons).FirstOrDefault(s => IdEquals(s.Id, parts[1]));
                json = season == null ? null : NodeJson(season);
            }
            else if (parts.Length == 3 && parts[0] == "sources" && parts[2] == "videos")
            {
                var season = content.Series.SelectMany(s => s.Seasons).FirstOrDefault(s => IdEquals(s.Id, parts[1]));
                json = season == null ? null : season.Episodes.Select(EpisodeJson).ToList();
            }
            else if (parts.Length == 2 && parts[0] == "videos")
            {
                var episode = content.Series.SelectMany(s => s.Seasons).SelectMany(s => s.Episodes).FirstOrDefault(e => IdEquals(e.Id, parts[1]));
                json = episode == null ? null : EpisodeJson(episode);
            }

            if (json == null)
            {
                result.Error = $"Introuvable dans la source locale : {path}";
                _logger.LogDebug("🗂️ [LOCAL SOURCE] 404 for {Path} (source '{Source}')", path, source?.Name);
                return result;
            }

            result.StatusCode = 200;
            result.Content = JsonSerializer.Serialize(json);
            return result;
        }

        private static bool IdEquals(string a, string b) => string.Equals(a, b, StringComparison.OrdinalIgnoreCase);

        private static Dictionary<string, object> NodeJson(LocalNode node)
        {
            var json = new Dictionary<string, object> { ["id"] = node.Id };
            Put(json, "title", node.Title);
            Put(json, "overview", node.Overview);
            Put(json, "premiereDate", node.PremiereDate);
            if (node.CommunityRating.HasValue)
            {
                json["communityRating"] = node.CommunityRating.Value;
            }

            if (node.Tags?.Count > 0) json["tags"] = node.Tags;
            if (node.Genres?.Count > 0) json["genres"] = node.Genres;
            Put(json, "poster", node.Poster);
            Put(json, "backdrop", node.Backdrop);
            Put(json, "banner", node.Banner);
            Put(json, "logo", node.Logo);
            Put(json, "thumb", node.Thumb);
            return json;
        }

        private Dictionary<string, object> EpisodeJson(LocalEpisode episode)
        {
            var json = NodeJson(episode);
            if (episode.IndexNumber.HasValue)
            {
                json["indexNumber"] = episode.IndexNumber.Value;
            }

            Put(json, "duration", episode.Duration);
            var cast = ResolveCast(episode);
            if (cast.Count > 0)
            {
                json["cast"] = cast;
            }

            if (!string.IsNullOrWhiteSpace(episode.PreviewUrl))
            {
                json["preview"] = new Dictionary<string, object> { ["url"] = episode.PreviewUrl };
            }

            return json;
        }

        /// <summary>Episode cast → cast list (name, role, type, order, photo), from the directory. Deleted person = skipped</summary>
        private List<Dictionary<string, object>> ResolveCast(LocalEpisode episode)
        {
            var result = new List<Dictionary<string, object>>();
            var people = _people?.Invoke();
            if (people == null || episode.Cast == null)
            {
                return result;
            }

            foreach (var entry in episode.Cast)
            {
                var person = people.Find(entry.PersonId);
                if (person == null)
                {
                    continue;
                }

                var item = new Dictionary<string, object> { ["name"] = person.Name, ["type"] = entry.Type ?? "Actor", ["order"] = result.Count };
                Put(item, "role", entry.Role);
                Put(item, "image", people.JellyfinPhotoUrl(person.Photo));
                result.Add(item);
            }

            return result;
        }

        private static void Put(Dictionary<string, object> json, string key, string value)
        {
            if (!string.IsNullOrWhiteSpace(value))
            {
                json[key] = value;
            }
        }
    }
