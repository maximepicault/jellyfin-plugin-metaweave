using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.Extensions.Logging;

namespace Jellyfin.Plugin.CustomMetadata.Services
{
    /// <summary>Identifier of a person in ONE people source (an identifier is only valid for its own source)</summary>
    public class PersonLink
    {
        /// <summary>Prefix of the people source ("pe")</summary>
        public string Prefix { get; set; }

        public string ExternalId { get; set; }
    }

    /// <summary>An entry of the directory: common to all sources, fed by APIs and/or typed by hand</summary>
    public class Person
    {
        /// <summary>Internal identifier generated by the plugin (referenced by the episodes' cast distributions)</summary>
        public string Id { get; set; }

        public string Name { get; set; }

        /// <summary>URL (http/https) or uploaded file ("local://img/people-directory/…")</summary>
        public string Photo { get; set; }

        public string Bio { get; set; }

        public List<PersonLink> Links { get; set; } = new List<PersonLink>();
    }

    public class PeopleDirectory
    {
        public int Version { get; set; } = 1;

        public List<Person> People { get; set; } = new List<Person>();
    }

    /// <summary>What a people source returns for an identifier</summary>
    public class PersonData
    {
        public string Name { get; set; }

        public string Photo { get; set; }

        public string Bio { get; set; }
    }

    /// <summary>
    /// Directory of people (cast), stored in DataFolderPath/people.json. Uploaded photos are stored like
    /// those of local sources, under the data id <see cref="ImagesDataId"/>.
    /// Deduplication: a person is recognised by one of their identifiers (source + id) or by their name,
    /// ignoring case, accents and punctuation.
    /// </summary>
    public class PeopleStore
    {
        public const string ImagesDataId = "people-directory";

        private static readonly JsonSerializerOptions FileOptions = new JsonSerializerOptions { WriteIndented = true, PropertyNameCaseInsensitive = true };
        private const string Alphabet = "abcdefghjkmnpqrstuvwxyz23456789";

        private readonly ILogger _logger;
        private readonly Func<string> _localApiUrl;
        private readonly LocalSourceStore _images;
        private readonly object _lock = new object();
        private (DateTime Stamp, PeopleDirectory Directory)? _cached;

        /// <param name="localApiUrl">Address of the Jellyfin server readable by itself ("http://127.0.0.1:8096"), for uploaded photos</param>
        public PeopleStore(ILogger logger, LocalSourceStore images, Func<string> localApiUrl = null)
        {
            _logger = logger;
            _images = images;
            _localApiUrl = localApiUrl;
        }

        private static string FilePath()
        {
            var root = Plugin.Instance?.DataFolderPath ?? Path.Combine(Path.GetTempPath(), "CustomMetadata");
            return Path.Combine(root, "people.json");
        }

        public PeopleDirectory Load()
        {
            lock (_lock)
            {
                var path = FilePath();
                if (!File.Exists(path))
                {
                    return new PeopleDirectory();
                }

                var stamp = File.GetLastWriteTimeUtc(path);
                if (_cached.HasValue && _cached.Value.Stamp == stamp)
                {
                    return _cached.Value.Directory;
                }

                try
                {
                    var directory = JsonSerializer.Deserialize<PeopleDirectory>(File.ReadAllText(path), FileOptions) ?? new PeopleDirectory();
                    directory.People ??= new List<Person>();
                    _cached = (stamp, directory);
                    return directory;
                }
                catch (Exception ex)
                {
                    _logger.LogError(ex, "👥 [PEOPLE] ❌ Cannot read {Path}", path);
                    return new PeopleDirectory();
                }
            }
        }

        public PeopleDirectory Save(PeopleDirectory directory)
        {
            directory ??= new PeopleDirectory();
            Normalize(directory);

            lock (_lock)
            {
                var path = FilePath();
                Directory.CreateDirectory(Path.GetDirectoryName(path));
                var tmp = path + ".tmp";
                File.WriteAllText(tmp, JsonSerializer.Serialize(directory, FileOptions));
                if (File.Exists(path))
                {
                    File.Copy(path, path + ".bak", true);
                }

                File.Move(tmp, path, true);
                _cached = (File.GetLastWriteTimeUtc(path), directory);
            }

            _images?.PruneImages(ImagesDataId, directory.People.Select(p => p.Photo));
            _logger.LogInformation("👥 [PEOPLE] 💾 Saved {Count} people", directory.People.Count);
            return directory;
        }

        /// <summary>Comparable name: lowercase, no accents, letters and digits separated by a single space</summary>
        public static string NormalizeName(string name)
        {
            if (string.IsNullOrWhiteSpace(name))
            {
                return string.Empty;
            }

            var decomposed = name.Normalize(NormalizationForm.FormD);
            var sb = new StringBuilder();
            foreach (var c in decomposed)
            {
                if (CharUnicodeInfo.GetUnicodeCategory(c) == UnicodeCategory.NonSpacingMark)
                {
                    continue;
                }

                sb.Append(char.IsLetterOrDigit(c) ? char.ToLowerInvariant(c) : ' ');
            }

            return Regex.Replace(sb.ToString(), @"\s+", " ").Trim();
        }

        /// <summary>Already known person: by identifier (source + id) first, otherwise by name</summary>
        public (Person Person, string Reason)? FindMatch(string prefix, string externalId, string name)
        {
            var people = Load().People;
            if (!string.IsNullOrEmpty(prefix) && !string.IsNullOrEmpty(externalId))
            {
                var byLink = people.FirstOrDefault(p => p.Links.Any(l => string.Equals(l.Prefix, prefix, StringComparison.OrdinalIgnoreCase)
                                                                         && string.Equals(l.ExternalId, externalId, StringComparison.OrdinalIgnoreCase)));
                if (byLink != null)
                {
                    return (byLink, "link");
                }
            }

            var normalized = NormalizeName(name);
            if (normalized.Length > 0)
            {
                var byName = people.FirstOrDefault(p => NormalizeName(p.Name) == normalized);
                if (byName != null)
                {
                    return (byName, "name");
                }
            }

            return null;
        }

        public Person Find(string personId)
        {
            return string.IsNullOrEmpty(personId) ? null : Load().People.FirstOrDefault(p => string.Equals(p.Id, personId, StringComparison.OrdinalIgnoreCase));
        }

        /// <summary>Photo → address Jellyfin can download. An uploaded file goes through the plugin's endpoint</summary>
        public string JellyfinPhotoUrl(string photo)
        {
            if (string.IsNullOrWhiteSpace(photo))
            {
                return null;
            }

            if (!LocalSourceStore.IsLocalImageUrl(photo))
            {
                return photo;
            }

            var api = _localApiUrl?.Invoke();
            return string.IsNullOrEmpty(api) ? null : $"{api.TrimEnd('/')}/CustomMetadata/People/Photo/{photo.Substring(photo.LastIndexOf('/') + 1)}";
        }

        /// <summary>Cast distribution (directory people + role/type) → cast read by the rest of the plugin. Deleted person = skipped</summary>
        public List<Api.CastMember> ResolveCast(IEnumerable<LocalCastEntry> entries)
        {
            var result = new List<Api.CastMember>();
            foreach (var entry in entries ?? Enumerable.Empty<LocalCastEntry>())
            {
                var person = Find(entry.PersonId);
                if (person == null)
                {
                    continue;
                }

                result.Add(new Api.CastMember { Name = person.Name, Role = entry.Role, Type = entry.Type ?? "Actor", Order = result.Count, Image = JellyfinPhotoUrl(person.Photo) });
            }

            return result;
        }

        private static string NewId(HashSet<string> used)
        {
            while (true)
            {
                var chars = new char[6];
                for (var i = 0; i < chars.Length; i++)
                {
                    chars[i] = Alphabet[RandomNumberGenerator.GetInt32(Alphabet.Length)];
                }

                var id = new string(chars);
                if (used.Add(id))
                {
                    return id;
                }
            }
        }

        private static string Clean(string text) => string.IsNullOrWhiteSpace(text) ? null : text.Trim();

        /// <summary>Ids generated or kept (unique), texts cleaned and decoded, source identifiers without duplicates</summary>
        public static void Normalize(PeopleDirectory directory)
        {
            directory.People ??= new List<Person>();
            directory.People = directory.People.Where(p => !string.IsNullOrWhiteSpace(p?.Name)).ToList();
            var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var links = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var person in directory.People)
            {
                var id = Clean(person.Id);
                person.Id = id != null && Regex.IsMatch(id, @"^\w{1,40}$") && used.Add(id) ? id : NewId(used);
                person.Name = Clean(HtmlText.Decode(person.Name));
                person.Bio = Clean(HtmlText.Decode(person.Bio));
                person.Photo = Clean(person.Photo);

                // An identifier (source + id) belongs to one person only: the first one that carries it keeps it
                person.Links = (person.Links ?? new List<PersonLink>())
                    .Where(l => !string.IsNullOrWhiteSpace(l?.Prefix) && !string.IsNullOrWhiteSpace(l.ExternalId))
                    .Select(l => new PersonLink { Prefix = l.Prefix.Trim().ToLowerInvariant(), ExternalId = l.ExternalId.Trim() })
                    .Where(l => links.Add(l.Prefix + "|" + l.ExternalId))
                    .ToList();
            }
        }
    }
}
