"""Fake demo API to test the plugin: python3 server.py <base_url> <img_dir> (listens on 0.0.0.0:8765)
Routes: /series/{id}, /sources/{id}, /sources/{id}/videos (episode list), /sources/longlist/videos (120 episodes in an object), /videos/{id}, /img/{file}"""
import json, urllib.parse, re, sys, os
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler
sys.path.insert(0, os.path.dirname(__file__)); from data import SERIES, OV, PEOPLE, DUMP, _DUMP_BRANDS
BASE = sys.argv[1]
IMG_DIR = sys.argv[2]  # folder of the images generated by gen.py
def vid_index():
    idx = {}
    for sid, s in SERIES.items():
        for nid, n in s["seasons"].items():
            for i, v in enumerate(n["videos"], 1):
                idx[f"{nid}v{i}"] = (sid, nid, i, v)
    return idx
VIDS = vid_index()
# Chapters in several shapes (time codes as text, as seconds, with a fraction), one past the end of the 2 s test videos
CHAPTERS = {
    # "end": the first ends BEFORE the next starts (a gap), the second ends exactly where the next starts, the third ends before the end of the video
    "d1v1": [{"time": "00:00", "end": 0.4, "title": "Introduction"}, {"time": 1, "end": "0:01.5", "title": "Milieu en secondes"}, {"time": "0:01.5", "end": "0:01.7", "title": "Fin"}, {"time": "0:30", "title": "Au-delà de la vidéo"}],
    "d1v3": [{"time": "0:00", "end": "12:34", "title": "Début"}, {"time": 754, "end": "1:02:03", "title": "Le débat"}, {"time": "1:02:03", "title": "Conclusion"}],   # a missing episode: no video, text in the synopsis
}
DOWNLOADS = {"b1v2": "b1v2.mp4", "b1v3": "b1v3.m3u8", "b1v4": "notvideo"}
def video_json(vid):
    sid, nid, i, (t, d, dur) = VIDS[vid]
    j = {"id": vid, "title": t, "overview": OV if i % 2 else None, "premiereDate": d, "indexNumber": i, "duration": dur, "thumb": f"{BASE}/img/{vid}.jpg"}
    if vid in CHAPTERS: j["chapters"] = CHAPTERS[vid]
    # Full videos offered for download (download-real.mjs): direct MP4, HLS playlist, and an HTML page
    if vid in DOWNLOADS: j["video"] = {"url": f"{BASE}/media/{DOWNLOADS[vid]}"}
    # Genres and tags with case variants and terms one would not want: the rules of the "Genres et tags" screen act on them
    if vid in ("d1v1", "d1v2"):
        j["genres"] = ["Docu", "DOCU", "Voyage", "Sponsorisé"]
        j["tags"] = ["tech", "Sponsorisé", "sponsorisé", "conférence"]
    # Time codes only in the synopsis (the option "read the chapters in the synopsis")
    if vid == "d1v2": j["overview"] = "Un épisode avec des repères dans le texte.\n0:00 Ouverture\n0:01 Suite du texte"
    return j
def dump_json():
    out = []
    for i, (did, name, brand, search, tags) in enumerate(DUMP):
        out.append({"id": did, "name": name, "slug": re.sub(r"[^a-z0-9]+", "-", search.lower()).strip("-")[:60] or str(did), "search_titles": search,
                    "description": f"<p>Synopsis de <b>{name}</b>.</p><ul><li>Premier point</li><li>Second point</li></ul>Fin&nbsp;du texte<br>Ligne&nbsp;2" if did != 1007 else "Texte &amp;amp; simple",
                    "tags": tags, "brand": _DUMP_BRANDS[brand], "brand_id": brand + 1,
                    "poster_url": f"{BASE}/img/dump{did}.jpg", "cover_url": f"{BASE}/img/dump{did}c.jpg",
                    "likes": 30 + i, "dislikes": 10 if i % 3 else 0, "views": 1000 + i, "downloads": i,
                    "released_at": f"{2018 + i % 7}-{1 + i % 12:02d}-{1 + i % 27:02d}T00:00:05.000Z", "released_at_unix": 1500000000 + i * 86400 * 30})
    return out
class H(BaseHTTPRequestHandler):
    HITS = {}
    def log_message(self, *a): pass
    def send(self, code, body, ctype="application/json"):
        data = body if isinstance(body, bytes) else json.dumps(body).encode()
        self.send_response(code); self.send_header("Content-Type", ctype); self.send_header("Content-Length", str(len(data))); self.end_headers(); self.wfile.write(data)
    def do_GET(self):
        p = self.path.split("?")[0]
        H.HITS[p] = H.HITS.get(p, 0) + 1
        if p == "/__hits": return self.send(200, H.HITS)
        if p == "/dump": return self.send(200, {"data": dump_json()})
        if p == "/dump-big":
            # A big catalogue (default 30000 entries) to time the matching
            n = int(urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query).get("n", ["30000"])[0])
            words = ["aurore", "foret", "nord", "phare", "riviere", "montagne", "desert", "ocean", "ville", "nuit", "jour", "voyage", "secret", "chemin", "ile", "vallee"]
            big = [{"id": 100000 + i, "name": "%s %s %s %d" % (words[i % 16].title(), words[(i // 16) % 16], words[(i // 256) % 16], i % 97),
                    "slug": "e%d" % i, "search_titles": "%s%s%s" % (words[i % 16], words[(i // 16) % 16], words[(i // 256) % 16]), "brand": "B%d" % (i % 20), "tags": ["t"]} for i in range(n)]
            return self.send(200, {"data": big})
        if p == "/dump-extra":
            # Both names hold the whole title; the second has more extra words
            return self.send(200, {"data": [
                {"id": 5001, "name": "Chemins hiver nordique grande finale saison speciale", "slug": "x1", "search_titles": "cheminshivernordiqueautretitre", "brand": "S"},
                {"id": 5002, "name": "Chemins hiver nordique finale", "slug": "x2", "search_titles": "cheminshivernordiqueautretitretrois", "brand": "S"}]})
        if p == "/dump-close":
            # Two entries of a series that both hold the file's title in their other titles; the main name of the first is much closer to it
            return self.send(200, {"data": [
                {"id": 4001, "name": "Chemins hiver sud profond", "slug": "k1", "search_titles": "cheminshivernordiqueautretitre", "brand": "S"},
                {"id": 4002, "name": "Chemins hiver nordique grand final", "slug": "k2", "search_titles": "cheminshivernordiqueautretitretrois", "brand": "S"}]})
        if p == "/dump-numafter":
            # The user's format: "other titles" = "{name} {episode number} {title 2} {title 3}", glued. The file's title is title 2 of every
            # episode (so it is found everywhere), and only the right episode has ITS number right after its own name
            data = []
            for n, name in enumerate(["Le depart", "La traversee", "Le col gele", "Le retour"], 1):
                fmt = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query).get("fmt", [""])[0]
                base = re.sub(r"[^a-z0-9]", "", name.lower())
                num = {"ep": "ep", "episode": "episode"}.get(fmt, "")
                # fmt=epbefore / episodebefore: the word and the number come BEFORE the name
                text = (("ep" if fmt == "epbefore" else "episode") + str(n) + base) if fmt in ("epbefore", "episodebefore") else base + num + str(n)
                data.append({"id": 3000 + n, "name": name, "slug": "n%d" % n, "search_titles": text + "cheminshivernordique" + "autretitre", "brand": "S"})
            return self.send(200, {"data": data})
        if p == "/dump-series":
            # One series whose episodes all hold the series title in their "other titles". flat=1: nothing tells the right episode apart
            flat = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query).get("flat", ["0"])[0] == "1"
            names = ["La traversee", "Le col gele", "Le grand froid"] if flat else ["Chemins hiver nordique grand final", "La traversee", "Le col gele"]
            return self.send(200, {"data": [{"id": 2001 + i, "name": n, "slug": "c%d" % i, "search_titles": "cheminshivernordique" + re.sub(r"[^a-z]", "", n.lower().replace("chemins hiver nordique", "")), "brand": "S"} for i, n in enumerate(names)]})
        if p == "/dump-bare": return self.send(200, dump_json())
        if p.startswith("/img/"):
            f = os.path.join(IMG_DIR, os.path.basename(p))
            return self.send(200, open(f, "rb").read(), "image/jpeg") if os.path.exists(f) else self.send(404, {})
        if p.startswith("/media/"):
            name = os.path.basename(p)
            if name == "notvideo": return self.send(200, b"<html><body>Please sign in</body></html>", "text/html")
            f = os.path.join(IMG_DIR, "media", name)
            ctype = {".m3u8": "application/vnd.apple.mpegurl", ".ts": "video/mp2t"}.get(os.path.splitext(name)[1], "application/octet-stream")
            if name == "b1v2.mp4" and os.path.exists(f):
                # Served slowly (about 0.4 MB/s) so that the downloads page has a running download to show
                import time
                data = open(f, "rb").read()
                self.send_response(200); self.send_header("Content-Type", ctype); self.send_header("Content-Length", str(len(data))); self.end_headers()
                for i in range(0, len(data), 65536):
                    self.wfile.write(data[i:i + 65536]); self.wfile.flush(); time.sleep(0.15)
                return
            return self.send(200, open(f, "rb").read(), ctype) if os.path.exists(f) else self.send(404, {})
        # A record whose fields are null / empty / missing, to exercise the fallback "a || b"
        m = re.fullmatch(r"/fallback/(\w+)", p)
        if m:
            return self.send(200, {"title": None, "name": "Nom de repli", "overview": "", "summary": "Résumé de repli", "tags": [],
                                   "categories": [{"label": "aventure"}, {"label": "nature"}], "genres_csv": "docu, voyage",
                                   "alt": "premier", "alt2": "second", "list": [{"label": "L1"}]})
        # People found through a SEARCH url: the answer is a LIST with one element (root list, or a list inside an object)
        if p in ("/people-list", "/people-wrapped"):
            uid = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query).get("user", [""])[0]
            if uid not in PEOPLE: return self.send(200, [] if p == "/people-list" else {"total": 0, "results": []})
            name, bio = PEOPLE[uid]
            if p == "/people-list":
                return self.send(200, [{"profile": {"displayName": name, "avatar": f"/img/{uid}.jpg", "about": bio}}])
            return self.send(200, {"total": 1, "results": [{"name": name, "photo": f"/img/{uid}.jpg", "bio": bio}]})
        # The photo path is inside a LIST of images, and the whole answer is a list too
        m = re.fullmatch(r"/people-images/(\w+)", p)
        if m and m[1] in PEOPLE:
            name, bio = PEOPLE[m[1]]
            return self.send(200, [{"name": name, "images": [{"file_path": f"/{m[1]}.jpg", "width": 300}, {"file_path": "/other.jpg", "width": 600}], "bio": bio}])
        # The photo is a PATH ("/p1.jpg"), to be completed with the address of an image server
        m = re.fullmatch(r"/people-path/(\w+)", p)
        if m and m[1] in PEOPLE:
            name, bio = PEOPLE[m[1]]
            return self.send(200, {"name": name, "profile_path": f"/{m[1]}.jpg", "bio": bio})
        m = re.fullmatch(r"/people/(\w+)", p)
        if m:
            if m[1] not in PEOPLE: return self.send(404, {"error": "inconnue"})
            name, bio = PEOPLE[m[1]]
            return self.send(200, {"name": name, "photo": f"/img/{m[1]}.jpg", "bio": bio})   # RELATIVE photo: completed with the base URL
        if p == "/series/echoheaders":   # returns the headers received, to check what really goes on the wire
            import json as _json
            return self.send(200, {"id": "echoheaders", "title": _json.dumps({k: v for k, v in self.headers.items()}, ensure_ascii=False)})
        m = re.fullmatch(r"/series/(cors[ABC])", p)
        if m:   # CORS-like backends: A refuses a request WITH an Origin, B one WITHOUT, C always
            origin = self.headers.get("Origin")
            refused = (m[1] == "corsA" and origin) or (m[1] == "corsB" and not origin) or m[1] == "corsC"
            if refused: return self.send(403, {"error": "Invalid CORS request"})
            return self.send(200, {"id": m[1], "title": "Réponse sans souci CORS", "overview": "ok"})
        m = re.fullmatch(r"/series/(\w+)", p)
        if m and m[1] == "bigimg":   # a poster of several MB: the source test must show it reduced, not refuse it
            return self.send(200, {"id": "bigimg", "title": "Grande affiche", "poster": f"{BASE}/img/big.jpg"})
        if m and m[1] in SERIES:
            return self.send(200, {"id": m[1], "title": SERIES[m[1]]["title"], "overview": "Série de démonstration.", "poster": f"{BASE}/img/{m[1]}.jpg"})
        # A LONG list inside an object (far more than the 20 KB the test screen keeps of the raw text): the clickable tree must still work
        if p == "/sources/longlist/videos":
            return self.send(200, {"total": 120, "data": {"videos": [
                # The FIRST episode is poor (no synopsis, no tags) and one in the middle is the richest: the example must be that one
                ({"id": f"long{i}", "title": f"Épisode long {i}"} if i == 1 else
                 {"id": f"long{i}", "title": f"Épisode long {i}", "overview": "Résumé très détaillé. " * 25, "meta": {"number": i, "length": "24:30"}, "tags": ["a", "b", "c"],
                  **({"rating": 4.5, "guest": {"name": "Invité", "role": "Expert"}, "deep": {"a": {"b": {"c": {"d": {"e": {"f": "profond"}}}}}}} if i == 57 else {}),
                  # fields that only OTHER episodes have: the example must still offer them
                  **({"sponsor": "Marque X", "meta": {"number": i, "length": "24:30", "award": "Prix du public"}} if i == 90 else {})})
                for i in range(1, 121)]}})
        m = re.fullmatch(r"/sources/(\w+)/videos", p)
        if m:
            for s in SERIES.values():
                if m[1] in s["seasons"]:
                    n = s["seasons"][m[1]]
                    if n.get("broken"): return self.send(500, {"error": "boom"})
                    items = [video_json(f"{m[1]}v{i}") for i in range(1, len(n["videos"]) + 1)]
                    if n.get("nonumbers"):
                        # No episode numbers, and the list is NOT in release order: the plugin must number by date position
                        for j in items: del j["indexNumber"]
                        items.reverse()
                    return self.send(200, items)
            return self.send(404, {})
        m = re.fullmatch(r"/sources/(\w+)", p)
        if m:
            for sid, s in SERIES.items():
                if m[1] in s["seasons"]:
                    return self.send(200, {"id": m[1], "title": s["seasons"][m[1]]["title"], "poster": f"{BASE}/img/{m[1]}.jpg"})
        m = re.fullmatch(r"/videos/(\w+)", p)
        if m and m[1] in VIDS:
            j = video_json(m[1])
            # The season of the unnumbered episodes (b1) gives no number on the single-video endpoint either
            if m[1].startswith("b1v"): j.pop("indexNumber", None)
            return self.send(200, j)
        self.send(404, {"error": "not found"})
ThreadingHTTPServer(("0.0.0.0", 8765), H).serve_forever()
