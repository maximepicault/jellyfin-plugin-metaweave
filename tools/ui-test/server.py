"""Fake demo API to test the plugin: python3 server.py <base_url> <img_dir> (listens on 0.0.0.0:8765)
Routes: /series/{id}, /sources/{id}, /sources/{id}/videos (episode list), /videos/{id}, /img/{file}"""
import json, urllib.parse, re, sys, os
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler
sys.path.insert(0, os.path.dirname(__file__)); from data import SERIES, OV, PEOPLE
BASE = sys.argv[1]
IMG_DIR = sys.argv[2]  # folder of the images generated by gen.py
def vid_index():
    idx = {}
    for sid, s in SERIES.items():
        for nid, n in s["seasons"].items():
            for i, v in enumerate(n["videos"], 1):
                idx[f"{nid}v{i}"] = (sid, nid, i, v)
    return idx
VIDS = vid_index()
def video_json(vid):
    sid, nid, i, (t, d, dur) = VIDS[vid]
    return {"id": vid, "title": t, "overview": OV if i % 2 else None, "premiereDate": d, "indexNumber": i, "duration": dur, "thumb": f"{BASE}/img/{vid}.jpg"}
class H(BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def send(self, code, body, ctype="application/json"):
        data = body if isinstance(body, bytes) else json.dumps(body).encode()
        self.send_response(code); self.send_header("Content-Type", ctype); self.send_header("Content-Length", str(len(data))); self.end_headers(); self.wfile.write(data)
    def do_GET(self):
        p = self.path.split("?")[0]
        if p.startswith("/img/"):
            f = os.path.join(IMG_DIR, os.path.basename(p))
            return self.send(200, open(f, "rb").read(), "image/jpeg") if os.path.exists(f) else self.send(404, {})
        # A record whose fields are null / empty / missing, to exercise the fallback "a || b"
        m = re.fullmatch(r"/fallback/(\w+)", p)
        if m:
            return self.send(200, {"title": None, "name": "Nom de repli", "overview": "", "summary": "Résumé de repli", "tags": [],
                                   "categories": [{"label": "aventure"}, {"label": "nature"}], "genres_csv": "docu, voyage",
                                   "alt": "premier", "alt2": "second", "list": [{"label": "L1"}]})
        # People found through a SEARCH url: the answer is a LIST with one element (root list, or a list inside an object)
        if p in ("/people-list", "/people-wrapped"):
            uid = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query).get("user", [""])[0]
            if uid not in PEOPLE: return self.send(200, [] if p == "/people-list" else {"total": 0, "results": []})
            name, bio = PEOPLE[uid]
            if p == "/people-list":
                return self.send(200, [{"profile": {"displayName": name, "avatar": f"/img/{uid}.jpg", "about": bio}}])
            return self.send(200, {"total": 1, "results": [{"name": name, "photo": f"/img/{uid}.jpg", "bio": bio}]})
        # The photo path is inside a LIST of images, and the whole answer is a list too
        m = re.fullmatch(r"/people-images/(\w+)", p)
        if m and m[1] in PEOPLE:
            name, bio = PEOPLE[m[1]]
            return self.send(200, [{"name": name, "images": [{"file_path": f"/{m[1]}.jpg", "width": 300}, {"file_path": "/other.jpg", "width": 600}], "bio": bio}])
        # The photo is a PATH ("/p1.jpg"), to be completed with the address of an image server
        m = re.fullmatch(r"/people-path/(\w+)", p)
        if m and m[1] in PEOPLE:
            name, bio = PEOPLE[m[1]]
            return self.send(200, {"name": name, "profile_path": f"/{m[1]}.jpg", "bio": bio})
        m = re.fullmatch(r"/people/(\w+)", p)
        if m:
            if m[1] not in PEOPLE: return self.send(404, {"error": "inconnue"})
            name, bio = PEOPLE[m[1]]
            return self.send(200, {"name": name, "photo": f"/img/{m[1]}.jpg", "bio": bio})   # RELATIVE photo: completed with the base URL
        if p == "/series/echoheaders":   # returns the headers received, to check what really goes on the wire
            import json as _json
            return self.send(200, {"id": "echoheaders", "title": _json.dumps({k: v for k, v in self.headers.items()}, ensure_ascii=False)})
        m = re.fullmatch(r"/series/(cors[ABC])", p)
        if m:   # CORS-like backends: A refuses a request WITH an Origin, B one WITHOUT, C always
            origin = self.headers.get("Origin")
            refused = (m[1] == "corsA" and origin) or (m[1] == "corsB" and not origin) or m[1] == "corsC"
            if refused: return self.send(403, {"error": "Invalid CORS request"})
            return self.send(200, {"id": m[1], "title": "Réponse sans souci CORS", "overview": "ok"})
        m = re.fullmatch(r"/series/(\w+)", p)
        if m and m[1] == "bigimg":   # a poster of several MB: the source test must show it reduced, not refuse it
            return self.send(200, {"id": "bigimg", "title": "Grande affiche", "poster": f"{BASE}/img/big.jpg"})
        if m and m[1] in SERIES:
            return self.send(200, {"id": m[1], "title": SERIES[m[1]]["title"], "overview": "Série de démonstration.", "poster": f"{BASE}/img/{m[1]}.jpg"})
        m = re.fullmatch(r"/sources/(\w+)/videos", p)
        if m:
            for s in SERIES.values():
                if m[1] in s["seasons"]:
                    n = s["seasons"][m[1]]
                    if n.get("broken"): return self.send(500, {"error": "boom"})
                    return self.send(200, [video_json(f"{m[1]}v{i}") for i in range(1, len(n["videos"]) + 1)])
            return self.send(404, {})
        m = re.fullmatch(r"/sources/(\w+)", p)
        if m:
            for sid, s in SERIES.items():
                if m[1] in s["seasons"]:
                    return self.send(200, {"id": m[1], "title": s["seasons"][m[1]]["title"], "poster": f"{BASE}/img/{m[1]}.jpg"})
        m = re.fullmatch(r"/videos/(\w+)", p)
        if m and m[1] in VIDS:
            return self.send(200, video_json(m[1]))
        self.send(404, {"error": "not found"})
ThreadingHTTPServer(("0.0.0.0", 8765), H).serve_forever()
