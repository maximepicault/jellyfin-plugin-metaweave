"""Fake demo API to test the plugin: python3 server.py <base_url> <img_dir> (listens on 0.0.0.0:8765)
Routes: /series/{id}, /sources/{id}, /sources/{id}/videos (episode list), /videos/{id}, /img/{file}"""
import json, re, sys, os
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler
sys.path.insert(0, os.path.dirname(__file__)); from data import SERIES, OV, PEOPLE
BASE = sys.argv[1]
IMG_DIR = sys.argv[2]  # folder of the images generated by gen.py
def vid_index():
    idx = {}
    for sid, s in SERIES.items():
        for nid, n in s["seasons"].items():
            for i, v in enumerate(n["videos"], 1):
                idx[f"{nid}v{i}"] = (sid, nid, i, v)
    return idx
VIDS = vid_index()
def video_json(vid):
    sid, nid, i, (t, d, dur) = VIDS[vid]
    return {"id": vid, "title": t, "overview": OV if i % 2 else None, "premiereDate": d, "indexNumber": i, "duration": dur, "thumb": f"{BASE}/img/{vid}.jpg"}
class H(BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def send(self, code, body, ctype="application/json"):
        data = body if isinstance(body, bytes) else json.dumps(body).encode()
        self.send_response(code); self.send_header("Content-Type", ctype); self.send_header("Content-Length", str(len(data))); self.end_headers(); self.wfile.write(data)
    def do_GET(self):
        p = self.path.split("?")[0]
        if p.startswith("/img/"):
            f = os.path.join(IMG_DIR, os.path.basename(p))
            return self.send(200, open(f, "rb").read(), "image/jpeg") if os.path.exists(f) else self.send(404, {})
        m = re.fullmatch(r"/people/(\w+)", p)
        if m:
            if m[1] not in PEOPLE: return self.send(404, {"error": "inconnue"})
            name, bio = PEOPLE[m[1]]
            return self.send(200, {"name": name, "photo": f"/img/{m[1]}.jpg", "bio": bio})   # RELATIVE photo: completed with the base URL
        m = re.fullmatch(r"/series/(\w+)", p)
        if m and m[1] in SERIES:
            return self.send(200, {"id": m[1], "title": SERIES[m[1]]["title"], "overview": "Série de démonstration.", "poster": f"{BASE}/img/{m[1]}.jpg"})
        m = re.fullmatch(r"/sources/(\w+)/videos", p)
        if m:
            for s in SERIES.values():
                if m[1] in s["seasons"]:
                    n = s["seasons"][m[1]]
                    if n.get("broken"): return self.send(500, {"error": "boom"})
                    return self.send(200, [video_json(f"{m[1]}v{i}") for i in range(1, len(n["videos"]) + 1)])
            return self.send(404, {})
        m = re.fullmatch(r"/sources/(\w+)", p)
        if m:
            for sid, s in SERIES.items():
                if m[1] in s["seasons"]:
                    return self.send(200, {"id": m[1], "title": s["seasons"][m[1]]["title"], "poster": f"{BASE}/img/{m[1]}.jpg"})
        m = re.fullmatch(r"/videos/(\w+)", p)
        if m and m[1] in VIDS:
            return self.send(200, video_json(m[1]))
        self.send(404, {"error": "not found"})
ThreadingHTTPServer(("0.0.0.0", 8765), H).serve_forever()
